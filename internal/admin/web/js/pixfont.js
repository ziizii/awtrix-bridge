// glyph returns the rows of one character, "?" for unknown ones.
export const glyph = ch => glyphs[ch] || glyphs["?"];

// normalize maps text to what the font can draw.
export const normalize = text =>
  String(text).normalize("NFD").replace(/[̀-ͯ]/g, "").toUpperCase();
